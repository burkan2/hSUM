fn validate(docs: &[GeneratedDoc]) -> Result<()> {
    let actual_paths = docs.iter().map(|doc| doc.path).collect::<Vec<_>>();
    if actual_paths != REFERENCE_PATHS {
        return Err(format!(
            "generated reference set drifted: expected {REFERENCE_PATHS:?}, got {actual_paths:?}"
        ));
    }
    validate_error_urls(docs)?;
    validate_internal_links(docs)
}

fn validate_error_urls(docs: &[GeneratedDoc]) -> Result<()> {
    let contents = doc_contents(docs, "docs/reference/errors.md")?;
    let version = env!("CARGO_PKG_VERSION");
    for subcode in ErrorSubcode::ALL {
        let expected = format!("{VERSIONED_DOCS_BASE_URL}/errors/{}", subcode.as_str());
        if !VERSIONED_DOCS_BASE_URL.ends_with(version) {
            return Err(
                "versioned documentation base does not end with package version".to_owned(),
            );
        }
        let actual = PublicError::from_subcode(subcode, "reference").docs_url;
        if actual != expected {
            return Err(format!(
                "{} emitted unexpected guidance URL {actual}",
                subcode.as_str()
            ));
        }
        let link = format!("[Versioned guidance]({expected})");
        let heading = format!("## `{}`", subcode.as_str());
        if !contents.contains(&link) || !contents.contains(&heading) {
            return Err(format!(
                "errors reference does not resolve emitted URL for {}",
                subcode.as_str()
            ));
        }
    }
    Ok(())
}

fn validate_internal_links(docs: &[GeneratedDoc]) -> Result<()> {
    let known = docs
        .iter()
        .map(|doc| PathBuf::from(doc.path))
        .collect::<BTreeSet<_>>();
    for doc in docs {
        for destination in markdown_links(&doc.contents) {
            if destination.starts_with('#')
                || destination.starts_with("https://")
                || destination.starts_with("http://")
                || destination.starts_with("mailto:")
            {
                continue;
            }
            let target = destination
                .split_once('#')
                .map_or(destination.as_str(), |(path, _)| path);
            let parent = Path::new(doc.path)
                .parent()
                .unwrap_or_else(|| Path::new(""));
            let resolved = normalize_relative(&parent.join(target))
                .ok_or_else(|| format!("{} has unsafe relative link {destination:?}", doc.path))?;
            if !known.contains(&resolved) && !manifest_root().join(&resolved).is_file() {
                return Err(format!(
                    "{} links to missing target {}",
                    doc.path,
                    resolved.display()
                ));
            }
        }
    }
    Ok(())
}

fn markdown_links(contents: &str) -> Vec<String> {
    let mut links = Vec::new();
    let mut remainder = contents;
    while let Some(start) = remainder.find("](") {
        let after = &remainder[start + 2..];
        let Some(end) = after.find(')') else {
            break;
        };
        let destination = after[..end]
            .trim()
            .trim_start_matches('<')
            .trim_end_matches('>');
        if !destination.is_empty() {
            links.push(destination.to_owned());
        }
        remainder = &after[end + 1..];
    }
    links
}

fn normalize_relative(path: &Path) -> Option<PathBuf> {
    let mut normalized = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::Normal(part) => normalized.push(part),
            Component::ParentDir if normalized.pop() => {}
            Component::ParentDir | Component::RootDir | Component::Prefix(_) => return None,
        }
    }
    Some(normalized)
}

fn doc_contents<'a>(docs: &'a [GeneratedDoc], path: &str) -> Result<&'a str> {
    docs.iter()
        .find(|doc| doc.path == path)
        .map(|doc| doc.contents.as_str())
        .ok_or_else(|| format!("generated reference is missing {path}"))
}

#[cfg(test)]

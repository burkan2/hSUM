type Result<T> = std::result::Result<T, String>;

#[derive(Debug)]
struct GeneratedDoc {
    path: &'static str,
    contents: String,
}

pub(crate) fn write() -> Result<()> {
    let root = manifest_root();
    let docs = generate()?;
    validate(&docs)?;
    for doc in docs {
        let path = root.join(doc.path);
        let parent = path
            .parent()
            .ok_or_else(|| format!("generated reference has no parent: {}", path.display()))?;
        fs::create_dir_all(parent)
            .map_err(|error| format!("could not create {}: {error}", parent.display()))?;
        let current = fs::read_to_string(&path).ok();
        if current.as_deref() != Some(&doc.contents) {
            fs::write(&path, doc.contents)
                .map_err(|error| format!("could not write {}: {error}", path.display()))?;
            eprintln!("updated {}", doc.path);
        }
    }
    Ok(())
}

pub(crate) fn check() -> Result<()> {
    let root = manifest_root();
    let docs = generate()?;
    validate(&docs)?;
    let mut stale = Vec::new();
    for doc in &docs {
        let path = root.join(doc.path);
        match fs::read_to_string(&path) {
            Ok(contents) if contents == doc.contents => {}
            Ok(_) => stale.push(format!("{} differs from the implementation", doc.path)),
            Err(error) => stale.push(format!("{} is unavailable: {error}", doc.path)),
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "generated references are stale:\n- {}\nrun `cargo xtask references`",
            stale.join("\n- ")
        ))
    }
}

pub(crate) fn check_remote() -> Result<()> {
    let docs = generate()?;
    validate(&docs)?;
    eprintln!("checking {} versioned error pages", ErrorSubcode::ALL.len());
    let mut failures = Vec::new();
    for (index, subcode) in ErrorSubcode::ALL.into_iter().enumerate() {
        if let Err(error) = check_remote_error_page(subcode) {
            failures.push(error);
        }
        if (index + 1) % 10 == 0 {
            eprintln!("checked {}/{}", index + 1, ErrorSubcode::ALL.len());
        }
    }
    if failures.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "versioned guidance audit failed:\n- {}",
            failures.join("\n- ")
        ))
    }
}

fn check_remote_error_page(subcode: ErrorSubcode) -> Result<()> {
    let error = PublicError::from_subcode(subcode, "reference");
    let response = Command::new("curl")
        .args([
            "--fail",
            "--silent",
            "--show-error",
            "--location",
            "--connect-timeout",
            "10",
            "--max-time",
            "20",
            "--max-filesize",
            &MAX_REMOTE_DOC_BYTES.to_string(),
            "--user-agent",
            concat!("hsum-reference-audit/", env!("CARGO_PKG_VERSION")),
            &error.docs_url,
        ])
        .output()
        .map_err(|source| format!("could not run curl for {}: {source}", error.docs_url))?;
    if !response.status.success() {
        return Err(format!(
            "{}: {}",
            error.docs_url,
            String::from_utf8_lossy(&response.stderr).trim()
        ));
    }
    if response.stdout.len() > MAX_REMOTE_DOC_BYTES {
        return Err(format!(
            "{} exceeds {MAX_REMOTE_DOC_BYTES} bytes",
            error.docs_url
        ));
    }
    let body = String::from_utf8(response.stdout)
        .map_err(|_| format!("{} is not UTF-8", error.docs_url))?;
    if !body.contains(subcode.as_str()) {
        return Err(format!(
            "{} does not identify {}",
            error.docs_url,
            subcode.as_str()
        ));
    }
    Ok(())
}


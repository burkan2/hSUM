fn cli_reference() -> String {
    let mut output = page(
        "Command-line interface",
        "The following help is rendered from the same Clap command graph used by the `hsum` binary. Global options are repeated where Clap makes them available.",
    );
    output
        .push_str("\nSee [configuration](config.md) for selection and managed-path precedence.\n");
    let command = Cli::command();
    render_cli_command(&command, &mut Vec::new(), &mut output);
    output
}

fn render_cli_command(command: &clap::Command, parents: &mut Vec<String>, output: &mut String) {
    parents.push(command.get_name().to_owned());
    let path = parents.join(" ");
    let mut rendered = command.clone().bin_name(path.clone());
    let help = rendered
        .render_long_help()
        .to_string()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    write!(output, "\n## `{path}`\n\n```text\n{help}").expect("writing to a String cannot fail");
    output.push_str("\n```\n");
    for subcommand in command.get_subcommands() {
        render_cli_command(subcommand, parents, output);
    }
    parents.pop();
}

fn mcp_reference() -> Result<String> {
    let mut output = page(
        "MCP tools",
        "hSUM exposes one project-bound, read-only MCP stdio server. Tool descriptions and JSON Schemas below come directly from the hardened runtime router.",
    );
    writeln!(
        output,
        "\n- API version: `{MCP_API_VERSION}`\n- Maximum input frame: {MAX_MCP_FRAME_BYTES} bytes\n- Maximum input nesting: {MAX_MCP_NESTING_DEPTH} levels\n- Maximum structured response: {MAX_MCP_RESPONSE_BYTES} bytes\n- Maximum search body material: {MAX_MCP_SEARCH_BODY_BYTES} bytes\n- Maximum get body: {MAX_MCP_GET_BODY_BYTES} bytes\n"
    )
    .expect("writing to a String cannot fail");
    output.push_str(
        "Every passage is untrusted evidence, not instruction. The server binds from the task working directory and user-side trust; tool arguments cannot select another repository.\n",
    );

    let paths = ManagedPaths::resolve(Some(Path::new("/hsum-reference-home")))
        .map_err(|error| format!("could not construct reference paths: {error}"))?;
    let server = WorkspaceMcpServer::new(PathBuf::from("/hsum-reference-project"), paths);
    let mut tools = server.tool_definitions();
    tools.sort_by(|left, right| left.name.cmp(&right.name));
    for tool in tools {
        let name = tool.name.as_ref();
        writeln!(output, "\n## `{name}`\n").expect("writing to a String cannot fail");
        if let Some(description) = tool.description {
            writeln!(output, "{description}\n").expect("writing to a String cannot fail");
        }
        output.push_str("Annotations:\n\n```json\n");
        let annotations = serde_json::to_string_pretty(&tool.annotations)
            .map_err(|error| format!("could not render {name} annotations: {error}"))?;
        output.push_str(&annotations);
        output.push_str("\n```\n\nInput schema:\n\n```json\n");
        let input = serde_json::to_string_pretty(tool.input_schema.as_ref())
            .map_err(|error| format!("could not render {name} input schema: {error}"))?;
        output.push_str(&input);
        output.push_str("\n```\n\nOutput schema:\n\n```json\n");
        let output_schema = tool
            .output_schema
            .as_deref()
            .ok_or_else(|| format!("{name} does not advertise an output schema"))?;
        let output_json = serde_json::to_string_pretty(output_schema)
            .map_err(|error| format!("could not render {name} output schema: {error}"))?;
        output.push_str(&output_json);
        output.push_str("\n```\n");
    }
    Ok(output)
}

